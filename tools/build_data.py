import json
from pathlib import Path

from PIL import Image, ImageStat

root = Path(__file__).resolve().parents[1]
bg = json.loads((root / "tools/backgrounds.json").read_text(encoding="utf-8"))
tracks = json.loads((root / "tools/tracks.json").read_text(encoding="utf-8"))


def luma(path: Path) -> float:
    im = Image.open(path).convert("L").resize((48, 48))
    return round(ImageStat.Stat(im).mean[0] / 255.0, 4)

# One accidental camera photo slipped into the pool; drop it and give the
# remaining frames honest titles.
rename = {
    "photo-1516339901601-2e1b62dc0c45": ("Emission", "Burning nebula in darkness", "space"),
    "photo-1495707902641-75cac588d2e9": ("Live", "A band under warm stage light", "music"),
}
backgrounds = []
for item in bg:
    pid = item["id"]
    if pid == "photo-1495707902641-75cac588d2e9":
        # this is actually a photo of a camera, not a neon scene
        continue
    title, alt, mood = rename.get(pid, (item["title"], item["alt"], item["mood"]))
    backgrounds.append({
        "file": f"assets/backgrounds/{item['file']}",
        "title": title,
        "alt": alt,
        "mood": mood,
        "source": f"https://images.unsplash.com/{pid}",
        "luma": luma(root / "assets" / "backgrounds" / item["file"]),
    })

js = []
js.append("/* Generated by tools/build_data.py — no build step is required at runtime. */")
js.append("(function () {")
js.append('  "use strict";')
js.append("  window.PRISM_DATA = {")
js.append("    backgrounds: " + json.dumps(backgrounds, ensure_ascii=False, indent=4).replace("\n", "\n    ") + ",")
js.append("    tracks: " + json.dumps(tracks, ensure_ascii=False, indent=4).replace("\n", "\n    ") + ",")
js.append("  };")
js.append("})();")
out = root / "js" / "data.js"
out.write_text("\n".join(js) + "\n", encoding="utf-8")

credits = [
    "# Background credits",
    "",
    "All background photographs are downloaded from [Unsplash](https://unsplash.com) and used under the",
    "[Unsplash License](https://unsplash.com/license). Attribution is not required by the license, but the",
    "source URL for each frame is listed below. The app works completely offline; the pool is pre-downloaded.",
    "",
    "| Frame | Title | Mood | Source |",
    "| --- | --- | --- | --- |",
]
for i, item in enumerate(backgrounds):
    credits.append(f"| {i+1:02d} | {item['title']} | {item['mood']} | [image]({item['source']}) |")
credits += [
    "",
    "The three demo tracks and their covers were synthesized from scratch for this project",
    "(see `tools/make_music.py`) and are free to use with the player.",
]
(root / "assets" / "backgrounds" / "CREDITS.md").write_text("\n".join(credits) + "\n", encoding="utf-8")
print(f"{len(backgrounds)} backgrounds, {len(tracks)} tracks -> {out}")
